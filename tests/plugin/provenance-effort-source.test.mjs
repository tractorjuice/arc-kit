/**
 * The provenance stamp works out Effective Effort from the model matrix, and
 * does not read `effort.level` from the hook input.
 *
 * The field looks like the better source, and `telemetry.mjs` reads it, but it
 * is the level in force when the hook fires, not the level the command ran at.
 * Every writer subagent runs at `medium` under a `high` or `max` command, and
 * the stamp rewrites its block on every later Write or Edit. Reading it would
 * mark those artefacts as downgraded because the "model does not support that
 * level", which is false, in a block people treat as audit evidence.
 *
 * It wouldn't catch the case it was proposed for either: on Claude Code
 * v2.1.319 a thinking-off Opus 5 session still reports `max`.
 *
 * NOTE the filename: CI runs `tests/plugin/*.test.mjs`.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const HOOK = resolve(__dirname, '../../plugins/arckit-claude/hooks/provenance-stamp.mjs');

/** Stamp a `/arckit:research` artefact (`effort: max`) with the given hook input. */
function stamp(hookInput) {
  const root = mkdtempSync(join(tmpdir(), 'prov-effort-'));
  const dir = join(root, 'projects', '001-t', 'research');
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'ARC-001-RSCH-001-v1.0.md');
  writeFileSync(file, '# T\n\n---\n\n**Generated by**: ArcKit `/arckit:research` command\n**Model**: claude-opus-5\n');
  execFileSync('node', [HOOK], {
    input: JSON.stringify({ cwd: root, tool_input: { file_path: file }, ...hookInput }),
    encoding: 'utf8',
  });
  return readFileSync(file, 'utf8');
}

function assertRanAsRequested(artefact) {
  assert.match(artefact, /Requested Effort \| `max`/);
  assert.match(artefact, /Effective Effort \| `max` \|/);
  assert.doesNotMatch(artefact, /downgraded/);
}

test('a writer subagent at medium is not a downgrade of a max command', () => {
  assertRanAsRequested(stamp({
    tool_name: 'Write',
    effort: { level: 'medium' },
    agent_type: 'arckit-research-writer',
    agent_id: 'agent-1',
  }));
});

test('a later edit at the session level is not a downgrade', () => {
  assertRanAsRequested(stamp({ tool_name: 'Edit', effort: { level: 'medium' } }));
});
