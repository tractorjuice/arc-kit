// The cells of a Markdown table row, split where GitHub splits them: at each pipe not escaped.
const cellsOf = (row) => {
  const cells = [];
  let current = '';
  for (let i = 1; i < row.length; i++) {
    if (row[i] === '\\') {
      current += row[i] + (row[i + 1] ?? '');
      i++;
    } else if (row[i] === '|') {
      cells.push(current.trim());
      current = '';
    } else current += row[i];
  }
  return cells;
};
