// A worksheet for a section in which the first method is not relevant, the second adapted and the
// rest apply, and the questions of the methods that apply are confirmed, proposed and left
// unanswered in turn, each answered with words no other question has.
const ANSWER_FOR = {
  'yes-no': () => 'yes', tick: () => 'no', 'yes-no-else': (id) => `Instead ${id}`,
  text: (id) => `Text ${id} | piped\nmore ${id}`, list: (id) => `Item ${id}\nSecond ${id}`
};
function generated(section) {
  const methods = new Map();
  const answers = new Map();
  const list = data.sections.get(section).methods;
  list.forEach((method, i) => {
    const records = [
      { status: 'not-relevant', reason: `We have no need of ${method.id}.`, decidedBy: 'Dee Cider' },
      { status: 'adapted', variation: `We vary ${method.id}.`, reason: `Because ${method.id}.`, provedSafe: `Tests of ${method.id}.`,
        decidedBy: 'Ada Apter' }
    ];
    methods.set(method.id, records[i] ?? { status: 'applies' });
  });
  let n = 0;
  for (const method of list.slice(1)) {
    for (const question of questionsOf(method).filter((q) => q.type !== 'note')) {
      const state = ['confirmed', 'proposed', 'unanswered'][n++ % 3];
      if (state === 'unanswered') continue;
      answers.set(question.id, {
        answer: ANSWER_FOR[question.type](question.id), state,
        by: state === 'confirmed' ? 'Tess Tester' : '', on: state === 'confirmed' ? '2026-11-17' : '',
        source: state === 'proposed' ? `the source for ${question.id}` : ''
      });
    }
  }
  return emitWorksheet({ data: DATA_ID, section, methods, answers, entries: new Map(), problems: [] }, data);
}

