#!/usr/bin/env node
/**
 * /arckit:pages publish guard: path-level gitignore filtering, and parity
 * between the canonical Claude hook and the hand-maintained Codex copy.
 *
 * 1. The guard used to ask git only about `projects/` and each project
 *    directory. A gitignored `vendors/` (or a single gitignored artefact) inside
 *    a published project still reached docs/manifest.json: path, H1 title,
 *    vendor names, and in dependencyGraph the full Document Control. Every
 *    candidate path now goes through one `git check-ignore --stdin` call.
 *
 * 2. extensions/arckit-codex/hooks/sync-guides.mjs is hand-maintained and never
 *    received the confidentiality defaults (gitignore guard, LLMS=true and
 *    VENDOR_SCORES=true opt-ins, stale llms.txt removal, CONFIDENTIALITY
 *    section), although the generated $arckit-pages skill promises them. The
 *    guard block must stay byte-identical in both copies, and both hooks are
 *    run against the same fixtures here.
 *
 * The Codex hook is run from a temporary plugin root that pairs its tracked
 * hooks/ with the canonical config/, docs/guides/ and templates/, so this suite
 * does not depend on scripts/converter.py having been run.
 */

import {
  mkdtempSync, rmSync, mkdirSync, writeFileSync, readFileSync, existsSync,
  readdirSync, copyFileSync, symlinkSync,
} from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import test, { after } from 'node:test';

const REPO = resolve(import.meta.dirname, '../..');
const CLAUDE_ROOT = join(REPO, 'plugins/arckit-claude');
const CODEX_HOOKS = join(REPO, 'extensions/arckit-codex/hooks');
const MARKER = '<!-- Generated by ArcKit /arckit:pages -->';

const codexRoot = mkdtempSync(join(tmpdir(), 'arckit-codex-root-'));
mkdirSync(join(codexRoot, 'hooks'));
for (const f of readdirSync(CODEX_HOOKS)) {
  if (f.endsWith('.mjs')) copyFileSync(join(CODEX_HOOKS, f), join(codexRoot, 'hooks', f));
}
mkdirSync(join(codexRoot, 'docs'));
symlinkSync(join(CLAUDE_ROOT, 'config'), join(codexRoot, 'config'));
symlinkSync(join(CLAUDE_ROOT, 'docs/guides'), join(codexRoot, 'docs/guides'));
symlinkSync(join(CLAUDE_ROOT, 'templates'), join(codexRoot, 'templates'));
after(() => rmSync(codexRoot, { recursive: true, force: true }));

const HOOKS = {
  claude: {
    script: join(CLAUDE_ROOT, 'hooks/sync-guides.mjs'),
    env: { CLAUDE_PLUGIN_ROOT: CLAUDE_ROOT },
    command: '/arckit:pages',
  },
  codex: {
    script: join(codexRoot, 'hooks/sync-guides.mjs'),
    env: { CODEX_PLUGIN_ROOT: codexRoot },
    command: '$arckit-pages',
  },
};

function git(cwd, ...args) {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`git ${args.join(' ')}: ${r.stderr}`);
}

function runHook(hook, repoRoot, args = '') {
  const env = { ...process.env, ...hook.env };
  delete env.CLAUDE_PLUGIN_ROOT;
  delete env.CODEX_PLUGIN_ROOT;
  Object.assign(env, hook.env);
  const r = spawnSync('node', [hook.script], {
    cwd: repoRoot,
    input: JSON.stringify({ prompt: `${hook.command}${args ? ` ${args}` : ''}`, cwd: repoRoot }),
    encoding: 'utf8',
    env,
    timeout: 60000,
  });
  assert.equal(r.status, 0, `hook failed: ${r.stderr}`);
  return JSON.parse(r.stdout).hookSpecificOutput.additionalContext;
}

const doc = (id, classification, extra = '') => `# ${id}

| Field | Value |
|-------|-------|
| **Document ID** | ${id} |
| **Owner** | Jane Architect |
| **Classification** | ${classification} |

${extra}
`;

// projects/001-tender is published; inside it vendors/ and one artefact are
// gitignored. projects/002-secret is gitignored as a whole. Nothing is
// committed under projects/, as in a real working tree mid-tender.
function withRepo(fn, { ignore = '', priorLlms = null } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'arckit-pages-guard-'));
  try {
    git(dir, 'init', '-q');
    writeFileSync(join(dir, '.gitignore'), ignore);
    const p = join(dir, 'projects/001-tender');
    mkdirSync(join(p, 'vendors/acme'), { recursive: true });
    mkdirSync(join(p, 'external'), { recursive: true });
    writeFileSync(join(p, 'ARC-001-REQ-v1.0.md'), doc('ARC-001-REQ-v1.0', 'OFFICIAL', 'FR-001 must hold.'));
    writeFileSync(join(p, 'ARC-001-RISK-v1.0.md'), doc('ARC-001-RISK-v1.0', 'OFFICIAL-SENSITIVE', 'See ARC-001-REQ-v1.0 and FR-001.'));
    writeFileSync(join(p, 'vendors/acme/proposal.md'), '# Acme Tender Proposal\n');
    writeFileSync(join(p, 'vendors/acme/ARC-001-RSCH-v1.0.md'), doc('ARC-001-RSCH-v1.0', 'OFFICIAL', 'FR-001'));
    writeFileSync(join(p, 'vendors/acme-profile.md'), '# Acme profile\n');
    writeFileSync(join(p, 'external/bid-pack.pdf'), 'pdf');
    writeFileSync(join(p, 'vendors/scores.json'), JSON.stringify({
      criteria: [{ id: 'C1', category: 'Technical', weight: 1 }],
      vendors: { acme: { displayName: 'Acme Ltd', scores: [{ criterionId: 'C1', score: 3 }], totalWeighted: 3 } },
    }));
    const s = join(dir, 'projects/002-secret');
    mkdirSync(s, { recursive: true });
    writeFileSync(join(s, 'ARC-002-REQ-v1.0.md'), doc('ARC-002-REQ-v1.0', 'OFFICIAL'));
    if (priorLlms !== null) {
      mkdirSync(join(dir, 'docs'), { recursive: true });
      writeFileSync(join(dir, 'docs/llms.txt'), priorLlms);
    }
    return fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const manifestOf = (dir) => JSON.parse(readFileSync(join(dir, 'docs/manifest.json'), 'utf8'));
const graphOf = (m) => m.dependencyGraph || { nodes: {}, edges: [] };

const GUARD_RE = /\/\/ ── Guard: never publish an index entry[\s\S]*?\/\/ ── END publish guard ──/;

test('the publish guard block is identical in the Claude and Codex hooks', () => {
  const claude = readFileSync(join(CLAUDE_ROOT, 'hooks/sync-guides.mjs'), 'utf8').match(GUARD_RE);
  const codex = readFileSync(join(CODEX_HOOKS, 'sync-guides.mjs'), 'utf8').match(GUARD_RE);
  assert.ok(claude, 'guard block missing from the Claude hook');
  assert.ok(codex, 'guard block missing from the Codex hook');
  assert.equal(codex[0], claude[0], 'Codex guard has drifted from the canonical hook');
});

test('both hooks call buildManifest with the omission counter', () => {
  for (const file of [join(CLAUDE_ROOT, 'hooks/sync-guides.mjs'), join(CODEX_HOOKS, 'sync-guides.mjs')]) {
    const src = readFileSync(file, 'utf8');
    assert.match(src, /dropGitIgnored\(repoRoot, allEntries, scan\)/, file);
    assert.doesNotMatch(src, /ignoredProjectDirs/, `${file} still has the directory-only guard`);
  }
});

for (const [name, hook] of Object.entries(HOOKS)) {
  test(`${name}: a gitignored vendors/ folder inside a published project is not indexed`, () => {
    withRepo((dir) => {
      const ctx = runHook(hook, dir, 'VENDOR_SCORES=true');
      const m = manifestOf(dir);
      const raw = JSON.stringify(m);
      assert.doesNotMatch(raw, /acme/i, 'vendor name, title or path leaked into manifest.json');
      const p = m.projects.find((x) => x.id === '001-tender');
      assert.ok(p, 'the published project is still indexed');
      assert.equal(p.vendors, undefined);
      assert.equal(p.vendorProfiles, undefined);
      assert.equal(p.vendorScores, undefined, 'a gitignored scores.json must not be ranked');
      for (const node of Object.values(graphOf(m).nodes)) {
        assert.equal(node.vendor ?? null, null, `vendor node ${node.path} leaked`);
      }
      assert.match(ctx, /gitignored file\(s\) inside published projects omitted/);
    }, { ignore: 'projects/*/vendors/\n' });
  });

  test(`${name}: a single gitignored artefact and external file are not indexed`, () => {
    withRepo((dir) => {
      runHook(hook, dir);
      const m = manifestOf(dir);
      const paths = m.projects.find((x) => x.id === '001-tender').documents.map((d) => d.path);
      assert.ok(paths.includes('projects/001-tender/ARC-001-REQ-v1.0.md'));
      assert.ok(!paths.includes('projects/001-tender/ARC-001-RISK-v1.0.md'), 'ignored artefact indexed');
      assert.doesNotMatch(JSON.stringify(m), /ARC-001-RISK|bid-pack/);
      const graph = graphOf(m);
      for (const e of graph.edges) {
        assert.ok(graph.nodes[e.from] && graph.nodes[e.to], `dangling edge ${e.from} -> ${e.to}`);
      }
    }, { ignore: 'projects/001-tender/ARC-001-RISK-v1.0.md\n*.pdf\n' });
  });

  test(`${name}: a gitignored project directory is not indexed or graphed`, () => {
    withRepo((dir) => {
      const ctx = runHook(hook, dir);
      const m = manifestOf(dir);
      assert.deepEqual(m.projects.map((p) => p.id), ['001-tender']);
      assert.doesNotMatch(JSON.stringify(m), /002-secret|ARC-002/, 'ignored project leaked (projects[], dependencyGraph or projectHealth)');
      assert.match(ctx, /\*\*1\*\* gitignored project director/);
    }, { ignore: 'projects/002-secret/\n' });
  });

  test(`${name}: an untracked but not ignored tree is fully indexed`, () => {
    withRepo((dir) => {
      runHook(hook, dir, 'VENDOR_SCORES=true');
      const m = manifestOf(dir);
      assert.equal(m.projects.length, 2);
      const p = m.projects.find((x) => x.id === '001-tender');
      assert.equal(p.vendors.length, 1);
      assert.ok(p.vendorScores);
      assert.ok(Object.values(graphOf(m).nodes).some((n) => n.vendor === 'acme'));
    });
  });

  test(`${name}: defaults leave out vendor scores and llms.txt and show CONFIDENTIALITY`, () => {
    withRepo((dir) => {
      const ctx = runHook(hook, dir);
      assert.equal(manifestOf(dir).projects.some((p) => p.vendorScores), false);
      assert.equal(existsSync(join(dir, 'docs/llms.txt')), false);
      assert.match(ctx, /### CONFIDENTIALITY/);
      assert.match(ctx, /Vendor scores: \*\*left out\*\* \(1 scored vendor/);
      assert.match(ctx, /ARC-001-RISK-v1\.0\.md` \(OFFICIAL-SENSITIVE\)/);
      assert.match(ctx, /not written \(opt in with LLMS=true\)/);
    });
  });

  test(`${name}: an llms.txt generated earlier is removed by default, written with LLMS=true`, () => {
    withRepo((dir) => {
      const ctx = runHook(hook, dir);
      assert.equal(existsSync(join(dir, 'docs/llms.txt')), false);
      assert.match(ctx, /removed — an earlier run generated it/);
      runHook(hook, dir, 'LLMS=true');
      assert.ok(readFileSync(join(dir, 'docs/llms.txt'), 'utf8').includes(MARKER));
    }, { priorLlms: `${MARKER}\n# old index\n` });
  });

  test(`${name}: the guard fails open outside a git repository`, () => {
    const dir = mkdtempSync(join(tmpdir(), 'arckit-nogit-'));
    try {
      mkdirSync(join(dir, 'projects/001-demo'), { recursive: true });
      writeFileSync(join(dir, 'projects/001-demo/ARC-001-REQ-v1.0.md'), '# Requirements\n');
      runHook(hook, dir);
      assert.equal(manifestOf(dir).projects.length, 1);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
}
